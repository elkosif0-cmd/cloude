  {std:"IAS 19", kws:["رواتب","أجور","اجور","نهاية خدمة","إجازات مستحقة","تأمينات اجتماعية مستحقة"]},
  {std:"IAS 21", kws:["عملة أجنبية","عملات أجنبي"]},
  {std:"IAS 24", kws:["شركاء","مسحوبات شخصية","سلف شخصية","شركة شقيقة"]},
  {std:"IAS 7",  kws:["نقدية","صندوق","بنك","مصرف"]},
  {std:"IAS 40", kws:["عقارات استثمار","أرض للاستثمار"]},
  {std:"IFRS 5", kws:["محتفظ به للبيع","معدة للبيع","نشاط متوقف"]},
  {std:"IAS 36", kws:["سمعة تجارية","اختبار انخفاض","انخفاض قيمة"]},
  {std:"IFRS 3", kws:["استحواذ","اندماج"]},
  {std:"AS1/BASE", kws:[]}
