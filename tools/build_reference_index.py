"""Reproduce the navigation index from frozen source-inspection fixtures; no network."""
import hashlib
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / 'tools/fixtures/verified-reference-index'
def read(name):
    return json.loads((INPUT / name).read_text())
reports, metadata, groups = read('companies.json'), read('metadata.json'), read('document-groups.json')
assert len(reports) == metadata['report_blocks'] == 50
assert len({r['company_id'] for r in reports}) == metadata['distinct_companies'] == 46
next_page = 2
for r in reports:
    assert r['from'] == next_page and r['page_count'] == r['to'] - r['from'] + 1
    next_page = r['to'] + 1
assert next_page == metadata['total_physical_pages'] + 1
hashes = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(INPUT.iterdir()) if p.is_file()}
output = '// Generated by tools/build_reference_index.py from frozen source-inspection inputs.\n'
for name, data in [('REFERENCE_REPORTS', reports), ('REFERENCE_METADATA', metadata), ('REFERENCE_DOCUMENT_GROUPS', groups), ('REFERENCE_INPUT_HASHES', hashes)]:
    output += 'export const ' + name + ' = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
target = ROOT / 'app/src/engine/fusion/reports/source-data/reference-index.ts'
if '--check' in sys.argv:
    assert target.read_text() == output, 'Reference index is stale: run python3 tools/build_reference_index.py'
    print('Reference index up to date: 50 reports / 46 companies / 12,506 physical pages')
else:
    target.write_text(output)
    print('Generated', target.relative_to(ROOT))
