import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const base = process.argv[2]; const out = process.argv[3];
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1400, height: 900 } });
await ctx.addInitScript(() => { try { sessionStorage.setItem('sqc_space_chosen', '1'); } catch {} });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
const tap = (sel) => p.waitForSelector(sel, { timeout: 20000 }).then(() => p.evaluate((s) => document.querySelector(s).click(), sel));
await p.goto(base + 'index.html', { waitUntil: 'domcontentloaded', timeout: 90000 });
await tap('#gate-list .gate[data-gate="accounting"]'); await tap('#sector-list .sector[data-sector="health"]'); await tap('#co-list .co[data-id="model-health"]');
await p.waitForURL(/\/app-safe(\.html)?([?#]|$)/, { timeout: 60000 });
await p.waitForFunction(() => window.SK && window.SKosifCore && window.SKosifLedger && SK.demo && SK.demo.settled() && !document.querySelector('.skdemo-overlay'), null, { timeout: 120000 });
await p.evaluate(() => SKosifLedger.open('claims')); await p.waitForTimeout(1500);
console.log(JSON.stringify(await p.evaluate(() => ({ families: [...document.querySelectorAll('[data-sk-tabs="ledger-family"] [data-tab]')].map((b) => b.dataset.tab + (b.classList.contains('active') ? '*' : '')), tabs: [...document.querySelectorAll('[data-sk-tabs="ledger"] [data-tab]')].map((b) => b.dataset.tab + (b.classList.contains('active') ? '*' : '')), all: SKosifLedger.tabs().length }))));
await p.screenshot({ path: out + '/r2-ledger-claims.jpg', type: 'jpeg', quality: 70 });
await p.evaluate(() => document.querySelector('[data-sk-tabs="ledger-family"] [data-tab="tax"]').click()); await p.waitForTimeout(800);
console.log(JSON.stringify(await p.evaluate(() => ({ tabs: [...document.querySelectorAll('[data-sk-tabs="ledger"] [data-tab]')].map((b) => b.dataset.tab + (b.classList.contains('active') ? '*' : '')) }))));
await p.screenshot({ path: out + '/r2-ledger-tax.jpg', type: 'jpeg', quality: 70 });
console.log('errors', errs.length ? errs.join(' | ') : 'none');
await browser.close();
