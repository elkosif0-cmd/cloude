def git(*args):
    try: return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace").stdout
    except Exception: return ""

def branch_rows():
    merged = set(l.strip() for l in git("branch", "-r", "--merged", "origin/main").splitlines() if l.strip() and "HEAD" not in l)
    out = []
    for line in git("for-each-ref", "refs/remotes/origin", "--format=%(refname:short)\t%(committerdate:short)\t%(subject)").splitlines():
        parts = line.split("\t")
        if len(parts) < 3 or parts[0].endswith("/HEAD") or parts[0] == "origin": continue
        name, date, subj = parts[0], parts[1], parts[2][:110]
        st = "MERGED في main" if name in merged else "أصل غير مدمج — يُقيَّم قبل أي حذف (FOUNDATION §0.0.1)"
        out.append({"kind": "branch", "repo": "cloude", "id": name, "name": name, "source": name, "description": subj, "classification": "—", "gateway": "", "also": [], "sector": "—",
                    "state": st, "dependencies": "—", "tests": [], "tests_count": 0, "duplicates": "—", "target": "—", "decision": "Retire (مدمج)" if name in merged else "Keep (أصل)", "migration": date,
                    "acceptance": "—", "risks": "—", "owner": "—", "next": "—"})
    return out

