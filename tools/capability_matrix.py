def camel(name):
    return re.sub(r"-([a-z])", lambda m: m.group(1).upper(), name)

def describe_engine(text):
    m = re.search(r"/\*\*?(.*?)\*/", text[:4000], re.S)
    if m:
        d = re.sub(r"\s+", " ", m.group(1).replace("*", " ")).strip()
        return d[:260]
    lines = [l.strip("/ ").strip() for l in text.splitlines()[:6] if l.strip().startswith("//")]
    return (" ".join(lines))[:260] or "—"

def engine_rows():
    rows = []
    src = ROOT / "app/src/engine/fusion"
    for dom in sorted(p.name for p in src.iterdir() if p.is_dir()):
        for f in sorted((src / dom).glob("*.ts")):
            if f.name.endswith(".test.ts") or f.name == "index.ts" or f.name.endswith(".d.ts"): continue
            name = f.name[:-3]
            short = re.sub(r"-engine$", "", name)
            fn = camel(short)
            text = read(f.relative_to(ROOT))
            test = (src / dom / (name + ".test.ts")).exists() or (src / dom / (short + ".test.ts")).exists()
            cons, n = consumers_of(dom, fn)
            imps, ni = engine_importers(dom, name)
            exports = len(re.findall(r"^export (?:function|const|class)", text, re.M))
            g, also = DOMAIN_CLASS.get(dom, ("accounting", []))
            if dom == "reports" and "source" in name: also = ["audit"]
            sector = "عام"
            low = name.lower()
            if any(k in low for k in ("carcass", "yield", "cut", "cold", "meat", "butcher")): sector = "اللحوم"
            elif any(k in low for k in ("recipe", "culinary", "blend", "box")): sector = "الأغذية (اللحوم، المخابز، المطاعم)"
            elif "zatca" in low or "vat" in low: sector = "السعودية/مصر (الضريبة)"
            rows.append({
                "kind": "engine", "repo": "cloude", "id": f"{dom}/{short}", "name": f"{dom}.{fn}", "source": f.relative_to(ROOT).as_posix(), "description": describe_engine(text),
                "classification": classify(g, also), "gateway": g, "also": also, "sector": sector, "state": ("مختبر (vitest)" if test else "بلا اختبار وحدة") + f" · {exports} تصديرات",
                "dependencies": ", ".join(sorted(set(re.findall(r"from '\./([a-z0-9-]+)'", text))))[:160] or "—",
                "tests": [f"app/src/engine/fusion/{dom}/{name}.test.ts"] if test else [], "tests_count": 1 if test else 0,
                "duplicates": "—", "target": "SKEngines." + dom + "." + fn + (f" ← {n} شاشة" if n else "") + (f" ← {ni} محرك يستورده" if ni else "") + ("" if n or ni else " ← لا شاشة ولا محرك يستهلكه (محرك بلا واجهة)"),
                "decision": "Keep" if n else ("Keep (مكتبة داخلية لمحركات أخرى)" if ni else "Relocate (ابنِ له مكاناً — FOUNDATION §0.0.0 قاعدة الاستفادة القصوى)"),
                "migration": "في main", "acceptance": "vitest" if test else "اختبار وحدة يُضاف", "risks": "—" if test else "بلا اختبار",
                "owner": "Claude", "next": "—" if n or ni else "إيجاد الشاشة/الأداة المناسبة أو توثيق سبب بقائه مكتبة داخلية",
                "consumers": cons, "consumers_count": n, "importers": imps, "importers_count": ni,
            })
    return rows

