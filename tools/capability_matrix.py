def md_table(rows, cols):
    head = "| " + " | ".join(h for h, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    body = "".join("| " + " | ".join(str(f(r)).replace("|", "¦").replace("\n", " ") for _, f in cols) + " |\n" for r in rows)
    return head + body

