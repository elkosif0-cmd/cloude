def read(p):
    try: return (ROOT / p).read_text(encoding="utf-8", errors="replace")
    except Exception: return ""

# ---------- the tests and screens that mention an id ----------
TEST_FILES = sorted([p for p in (ROOT / "tools").glob("*.mjs")] + [p for p in (ROOT / "tools").glob("*.py")] + list((ROOT / "app/src").rglob("*.test.ts")))
TEST_TEXT = {p: read(p.relative_to(ROOT)) for p in TEST_FILES}
UI_FILES = sorted([p for p in (ROOT / "ui").rglob("*.js") if "legacy" not in p.parts and "vendor" not in p.parts and p.name != "engines.js"])
UI_TEXT = {p: read(p.relative_to(ROOT)) for p in UI_FILES}

def tests_for(token, limit=6):
    pat = re.compile(r"(?<![A-Za-z0-9_])" + re.escape(token) + r"(?![A-Za-z0-9_])")
    hits = [p.relative_to(ROOT).as_posix() for p, t in TEST_TEXT.items() if pat.search(t)]
    return hits[:limit], len(hits)

def consumers_of(dom, fn, limit=6):
    """the screens that call an engine: SKEngines.<dom>.<fn>, or <dom>.<fn> through a local alias (E().reports.x, const R=SKEngines.reports)"""
    pat = re.compile(r"(?<![A-Za-z0-9_])" + re.escape(dom) + r"\." + re.escape(fn) + r"(?![A-Za-z0-9_])")
    hits = [p.relative_to(ROOT).as_posix() for p, t in UI_TEXT.items() if pat.search(t)]
    return hits[:limit], len(hits)

ENGINE_FILES = sorted((ROOT / "app/src/engine/fusion").rglob("*.ts"))
ENGINE_TEXT = {p: read(p.relative_to(ROOT)) for p in ENGINE_FILES if not p.name.endswith(".test.ts") and p.name != "index.ts"}
def engine_importers(dom, name, limit=6):
    """the other engines that import this one (a library engine is consumed through them)"""
    pat = re.compile(r"from '(?:\./|\.\./" + re.escape(dom) + r"/)" + re.escape(name) + r"'")
    hits = [p.relative_to(ROOT).as_posix() for p, t in ENGINE_TEXT.items() if pat.search(t) and p.name != name + ".ts"]
    return hits[:limit], len(hits)

