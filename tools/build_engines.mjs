// Compile the tested engines in app/src/engine/fusion into one browser file:
//   ui/core/engines.js  →  window.SKEngines.<domain>.<engine>.<fn>
// Run from the repo root after `npm ci` in app/:  node tools/build_engines.mjs [--check]
import { readdirSync, writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root); // region comments in the output are relative to the working directory
const src = join(root, 'app/src/engine/fusion');
const lines = ['// generated by tools/build_engines.mjs — do not edit'];
const ns = {};
for (const dom of readdirSync(src, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
  for (const f of readdirSync(join(src, dom)).sort()) {
    if (!f.endsWith('.ts') || f.endsWith('.test.ts')) continue;
    const name = f.replace(/-engine\.ts$|\.ts$/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
    const id = `${dom}_${name}`;
    lines.push(`import * as ${id} from './${dom}/${f.replace(/\.ts$/, '')}';`);
    (ns[dom] ||= []).push(`${name}:${id}`);
  }
}
lines.push('export default {' + Object.entries(ns).map(([d, xs]) => `${d}:{${xs.join(',')}}`).join(',') + '};');
writeFileSync(join(src, 'index.ts'), lines.join('\n') + '\n');
const { build } = await import(pathToFileURL(join(root, 'app/node_modules/vite/dist/node/index.js')).href);
const outDir = join(root, 'app/.engines-build');
await build({ root: join(root, 'app'), logLevel: 'error', configFile: false,
  build: { outDir, emptyOutDir: true, minify: false, target: 'es2020',
    lib: { entry: join(src, 'index.ts'), name: 'SKEngines', formats: ['iife'], fileName: () => 'engines.js' } } });
const banner = '/* S.kosif engines — compiled from app/src/engine/fusion (tested in CI with vitest).\n   Generated by tools/build_engines.mjs; do not edit by hand. */\n';
const body = readFileSync(join(outDir, 'engines.js'), 'utf8').replace(/^var SKEngines/m, 'window.SKEngines');
const out = banner + body;
const target = join(root, 'ui/core/engines.js');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) { console.error('ui/core/engines.js is stale: run node tools/build_engines.mjs'); process.exit(1); }
  console.log('engines up to date');
} else { mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, out); console.log('wrote ui/core/engines.js', out.length); }
