// Compile the tested engines in app/src/engine/fusion into the browser files:
//   ui/core/engines.js          →  window.SKEngines.<domain>.<engine>.<fn>   (in the app bundle, every screen)
//   ui/data/engines-sources.js  →  the reviewed published-source adapters (McDonald's, Volkswagen, Mercedes, Home Depot and the
//                                  reference index: 2.4 MB of embedded report data that no screen reads at start). They join
//                                  window.SKEngines.reports when the file is loaded — by SKEngines.loadSources() in the browser,
//                                  or by tools/apple-source-harness.mjs in the tests. (R4, docs/rebuild/DEEP_REVIEW_20261007_ar.md)
// Run from the repo root after `npm ci` in app/:  node tools/build_engines.mjs [--check]
import { readdirSync, writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root); // region comments in the output are relative to the working directory
const src = join(root, 'app/src/engine/fusion');
/* the source adapters kept out of the app bundle: self-contained (type-only imports), read only by the source tests */
const SOURCES = new Set(['reports/home-depot-source-engine.ts', 'reports/mercedes-source-engine.ts', 'reports/published-mcdonalds-source-engine.ts',
  'reports/reference-index-engine.ts', 'reports/volkswagen-source-engine.ts']);
const lines = ['// generated by tools/build_engines.mjs — do not edit'];
const srcLines = ['// generated by tools/build_engines.mjs — do not edit (the source adapters, ui/data/engines-sources.js)'];
const ns = {}, sns = {};
for (const dom of readdirSync(src, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
  for (const f of readdirSync(join(src, dom)).sort()) {
    if (!f.endsWith('.ts') || f.endsWith('.test.ts')) continue;
    const name = f.replace(/-engine\.ts$|\.ts$/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
    const id = `${dom}_${name}`, line = `import * as ${id} from './${dom}/${f.replace(/\.ts$/, '')}';`;
    if (SOURCES.has(`${dom}/${f}`)) { srcLines.push(line); (sns[dom] ||= []).push(`${name}:${id}`); }
    else { lines.push(line); (ns[dom] ||= []).push(`${name}:${id}`); }
  }
}
const exportOf = (o) => 'export default {' + Object.entries(o).map(([d, xs]) => `${d}:{${xs.join(',')}}`).join(',') + '};';
lines.push(exportOf(ns)); srcLines.push(exportOf(sns));
writeFileSync(join(src, 'index.ts'), lines.join('\n') + '\n');
writeFileSync(join(src, 'sources.ts'), srcLines.join('\n') + '\n');
const { build } = await import(pathToFileURL(join(root, 'app/node_modules/vite/dist/node/index.js')).href);
async function compile(entry, name) {
  const outDir = join(root, 'app/.engines-build', name);
  await build({ root: join(root, 'app'), logLevel: 'error', configFile: false,
    build: { outDir, emptyOutDir: true, minify: false, target: 'es2020',
      lib: { entry: join(src, entry), name, formats: ['iife'], fileName: () => 'out.js' } } });
  return readFileSync(join(outDir, 'out.js'), 'utf8');
}
const banner = '/* S.kosif engines — compiled from app/src/engine/fusion (tested in CI with vitest).\n   Generated by tools/build_engines.mjs; do not edit by hand. */\n';
/* SKEngines.loadSources(): the source adapters on demand (one request, then the same promise) */
const loader = '\n/* the reviewed published-source adapters live in ./data/engines-sources.js (R4: kept out of the app bundle) */\n' +
  'window.SKEngines.loadSources=function(){var E=window.SKEngines;if(E.reports&&E.reports.volkswagenSource)return Promise.resolve(E);' +
  'return E.__sources||(E.__sources=new Promise(function(ok,no){var s=document.createElement("script");s.src="./data/engines-sources.js";' +
  's.onload=function(){ok(window.SKEngines)};s.onerror=function(e){E.__sources=null;no(e)};document.head.appendChild(s)}))};\n';
const out = banner + (await compile('index.ts', 'SKEngines')).replace(/^var SKEngines/m, 'window.SKEngines') + loader;
const sourcesOut = '/* S.kosif engines — the reviewed published-source adapters (McDonald\'s, Volkswagen, Mercedes, Home Depot, reference index).\n' +
  '   Generated by tools/build_engines.mjs; do not edit by hand. Loaded after ui/core/engines.js; joins window.SKEngines.reports. */\n' +
  (await compile('sources.ts', 'SKEngineSources')) +
  ';(function(){var E=window.SKEngines=window.SKEngines||{},S=SKEngineSources.default||SKEngineSources;for(var d in S){E[d]=Object.assign(E[d]||{},S[d])}})();\n';
const targets = [[join(root, 'ui/core/engines.js'), out], [join(root, 'ui/data/engines-sources.js'), sourcesOut]];
if (process.argv.includes('--check')) {
  for (const [t, body] of targets) if (!existsSync(t) || readFileSync(t, 'utf8') !== body) { console.error(t.replace(root, '').replace(/\\/g, '/') + ' is stale: run node tools/build_engines.mjs'); process.exit(1); }
  console.log('engines up to date');
} else {
  for (const [t, body] of targets) { mkdirSync(dirname(t), { recursive: true }); writeFileSync(t, body); console.log('wrote', t.replace(root, '').replace(/\\/g, '/'), body.length); }
}
